/**
 * Detect browser language code (e.g. 'zh-CN' -> 'zh') with fallback to 'en'
 */
export function detectBrowserLanguage() {
  const rawLang =
    (typeof chrome !== 'undefined' && chrome.i18n && typeof chrome.i18n.getUILanguage === 'function'
      ? chrome.i18n.getUILanguage()
      : navigator.language) || 'en';

  const normalized = rawLang.toLowerCase();
  const base = normalized.split(/[-_]/)[0];

  if (TRANSLATIONS[normalized]) return normalized;
  if (TRANSLATIONS[base]) return base;
  return 'en';
}

export function resolveLanguage(pref = 'system') {
  if (!pref || pref === 'system') {
    return detectBrowserLanguage();
  }
  if (TRANSLATIONS[pref]) {
    return pref;
  }
  const base = String(pref).toLowerCase().split(/[-_]/)[0];
  return TRANSLATIONS[base] ? base : 'en';
}

/**
 * Translate key with interpolation and fallback to English
 */
export function translate(langPref, key, params = {}) {
  const lang = resolveLanguage(langPref);
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let template = dict[key] !== undefined ? dict[key] : TRANSLATIONS.en[key] || key;

  for (const [k, v] of Object.entries(params)) {
    template = template.replaceAll(`{${k}}`, String(v));
  }
  return template;
}
